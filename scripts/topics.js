const comparisonSlugs = [...new Set(Object.values(categories).flat())];

if (comparisonSlugs.length < 100) {
  throw new Error(`Expected at least 100 unique comparison topics, found ${comparisonSlugs.length}.`);
}

const comparisonSlugSet = new Set(comparisonSlugs);
const reversedComparisons = comparisonSlugs.filter((slug) => {
  const [toolA, toolB] = slug.split("-vs-");
  return comparisonSlugSet.has(`${toolB}-vs-${toolA}`);
});

if (reversedComparisons.length > 0) {
  throw new Error(`Comparison topics must not include reversed duplicates: ${reversedComparisons.join(", ")}.`);
}

